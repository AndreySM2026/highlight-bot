from __future__ import annotations

JSON_RULES = """Ответь ТОЛЬКО валидным JSON без markdown и без текста до или после него.
Внутри строковых значений НЕ используй двойные кавычки " — для цитат и названий только «ёлочки».
Между объектами в массиве — запятые, после последнего элемента запятой нет."""


def retry_note(attempt: int) -> str:
    """
    Пометка для повторной попытки. Агент TimeWeb возвращает на одинаковый запрос тот же ответ,
    поэтому повтор без изменений повторяет и сломанный JSON.
    """
    if attempt <= 1:
        return ""
    return (
        f"\n\n(Попытка {attempt}. Предыдущий ответ не удалось разобрать как JSON. "
        "Проверь кавычки внутри строк и запятые между объектами.)"
    )
